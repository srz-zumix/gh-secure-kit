// Package hook implements the "secret-scanning local hook" commands, which
// manage the git hooks that run local secret scanning.
package hook

import (
	"fmt"

	"github.com/cli/cli/v2/pkg/cmdutil"
	"github.com/spf13/cobra"
	"github.com/srz-zumix/gh-secure-kit/internal/localscan"
	"github.com/srz-zumix/go-gh-extension/pkg/logger"
)

// NewInstallCmd returns the secret-scanning local hook install command
func NewInstallCmd() *cobra.Command {
	var (
		path       string
		force      bool
		backup     bool
		merge      bool
		logLevel   string
		verify     bool
		verifyHost string
		exclude    []string
	)

	cmd := &cobra.Command{
		Use:   "install [pre-commit|pre-push]...",
		Short: "Install git hooks that run local secret scanning",
		Long: `Install git hooks that run 'secret-scanning local check' before a commit or a push.
Only the pre-push hook is installed when no hook name is given, which is enough to stop a secret from reaching the remote.
The pre-commit hook scans staged changes and the pre-push hook scans unpushed commits, aborting the operation when a secret is found.
Use --hook-log-level to set the log level the installed hook runs the scan with.
Use --hook-verify to enable token validity checks in the installed hook; supported tokens are sent to their providers' official APIs. This is disabled by default and adds network latency.
Use --hook-verify-host HOST with --hook-verify to check GitHub tokens on both github.com and a specific GHES hostname.
Use --hook-exclude with --hook-verify to omit findings with selected statuses from output and allow the operation when no other findings remain. Accepts active, inactive, unknown, and unsupported; separate multiple values with commas or repeat the flag. By default, no statuses are excluded.
An existing hook that was not generated by this tool is kept unless --merge, --force or --backup is given.
Use --merge to insert the scan as a delimited block right after the shebang of an existing POSIX shell hook (for example the pre-push hook created by 'git lfs install'), keeping the rest of the hook intact; the pre-push block buffers the refs git supplies on stdin and replays them to the rest of the hook.
Re-running install on a hook with a merged block updates only that block.`,
		ValidArgs: localscan.HookNames,
		Args:      cobra.OnlyValidArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := localscan.ValidateVerificationOptions(verify, exclude, verifyHost); err != nil {
				return err
			}
			if len(args) == 0 {
				args = localscan.DefaultInstallHookNames
			}
			names, err := localscan.ResolveHookNames(args)
			if err != nil {
				return err
			}
			dir, err := localscan.HooksDir(path)
			if err != nil {
				return fmt.Errorf("failed to resolve the git hooks directory: %w", err)
			}
			// An empty log level keeps the --log-level flag out of the generated hook.
			for _, name := range names {
				hookPath, err := localscan.InstallHook(dir, name, localscan.InstallHookOptions{Force: force, Backup: backup, Merge: merge, LogLevel: logLevel, Verify: verify, VerifyHost: verifyHost, Exclude: exclude})
				if err != nil {
					return fmt.Errorf("failed to install the %s hook: %w", name, err)
				}
				logger.Info("installed git hook", "hook", name, "path", hookPath)
			}
			return nil
		},
	}

	f := cmd.Flags()
	f.StringVar(&path, "path", ".", "The repository path to install the hooks into")
	f.BoolVar(&force, "force", false, "Overwrite an existing hook that is not managed by gh-secure-kit")
	f.BoolVar(&backup, "backup", false, "Move an existing hook aside to <hook>.gh-secure-kit.bak before installing")
	f.BoolVar(&merge, "merge", false, "Insert the scan into an existing POSIX shell hook that is not managed by gh-secure-kit instead of replacing it")
	f.BoolVar(&verify, "hook-verify", false, "Enable --verify in installed hooks (sends supported tokens to official APIs and adds network latency)")
	f.StringVar(&verifyHost, "hook-verify-host", "", "Additional GitHub hostname to check alongside github.com in installed hooks (requires --hook-verify)")
	cmdutil.StringSliceEnumFlag(cmd, &exclude, "hook-exclude", "", nil, localscan.ValidityStatuses, "Exclude findings with these statuses in installed hooks (comma-separated or repeated; requires --hook-verify)")
	logLevelFlag := logger.AddCmdFlag(cmd, f, &logLevel, "hook-log-level", "")
	// The hook inherits the log level of whoever runs it unless one is requested,
	// so drop the default the shared flag helper applies.
	logLevel = ""
	logLevelFlag.DefValue = ""
	logLevelFlag.Usage += " of the scan run by the installed hook"
	cmd.MarkFlagsMutuallyExclusive("force", "backup", "merge")

	return cmd
}
