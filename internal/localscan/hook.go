// HookNames lists the git hooks that can be managed by this tool.
var HookNames = []string{"pre-commit", "pre-push"}

// DefaultInstallHookNames lists the hooks installed when none are requested.
// Scanning on push is enough to stop a secret from reaching the remote, and
// avoids the cost of scanning on every commit.
var DefaultInstallHookNames = []string{"pre-push"}

// hookMarker identifies hook scripts generated by this tool.
const hookMarker = "gh-secure-kit:secret-scanning-local"

// hookBackupSuffix is appended to an existing hook moved aside on install.
const hookBackupSuffix = ".gh-secure-kit.bak"

// mergeBeginMarker and mergeEndMarker delimit the block merged into an
// existing hook script by install --merge.
const (
	mergeBeginMarker = "# >>> " + hookMarker + " >>>"
	mergeEndMarker   = "# <<< " + hookMarker + " <<<"
)

// mergeableShells lists the interpreters whose hook scripts can host the
// merged POSIX sh block.
var mergeableShells = []string{"sh", "bash", "dash", "zsh", "ksh", "ash"}

// HookState describes the installation state of a single git hook.
type HookState string

const (
	// HookStateInstalled means the hook exists and was generated by this tool.
	HookStateInstalled HookState = "installed"
	// HookStateNotInstalled means no hook file exists.
	HookStateNotInstalled HookState = "not_installed"
	// HookStateUnmanaged means a hook file exists but was not generated by this tool.
	HookStateUnmanaged HookState = "unmanaged"
	// HookStateMerged means the scan block was merged into a hook script that
	// was not generated by this tool.
	HookStateMerged HookState = "merged"
)

// HookStatus reports the state of a single git hook.
type HookStatus struct {
	Name  string    `json:"name"`
	Path  string    `json:"path"`
	State HookState `json:"state"`
}

// InstallHookOptions controls how an existing, unmanaged hook file is handled.
type InstallHookOptions struct {
	Force  bool
	Backup bool
	// Merge inserts the scan block into an existing sh-compatible hook script
	// instead of replacing it.
	Merge      bool
	Verify     bool
	VerifyHost string
	Exclude    []string
	// LogLevel, when set, is passed as --log-level to the check command the
	// generated hook runs.
	LogLevel string
}

// ResolveHookNames validates the requested hook names, returning all
// supported hooks when none are given.
func ResolveHookNames(names []string) ([]string, error) {
	if len(names) == 0 {
		return slices.Clone(HookNames), nil
	}
	for _, n := range names {
		if !slices.Contains(HookNames, n) {
			return nil, fmt.Errorf("unsupported hook %q, expected one of %s", n, strings.Join(HookNames, ", "))
		}
	}
	return slices.Clone(names), nil
}

// HooksDir resolves the directory git reads hooks from for the repository at
// repoPath, honoring the core.hooksPath configuration.
func HooksDir(repoPath string) (string, error) {
	repo, err := git.PlainOpenWithOptions(repoPath, &git.PlainOpenOptions{DetectDotGit: true})
	if err != nil {
		return "", fmt.Errorf("failed to open git repository at %q: %w", repoPath, err)
	}
	worktree, err := repo.Worktree()
	if err != nil {
		return "", fmt.Errorf("failed to resolve worktree for %q: %w", repoPath, err)
	}
	root := worktree.Filesystem.Root()

	cfg, err := repo.ConfigScoped(config.SystemScope)
	if err != nil {
		return "", fmt.Errorf("failed to read git configuration for %q: %w", repoPath, err)
	}
	if hooksPath := cfg.Raw.Section("core").Option("hooksPath"); hooksPath != "" {
		if filepath.IsAbs(hooksPath) {
			return hooksPath, nil
		}
		return filepath.Join(root, hooksPath), nil
	}

	gitDir, err := resolveGitDir(root)
	if err != nil {
		return "", err
	}
	return filepath.Join(gitDir, "hooks"), nil
}

// InstallHook writes the hook script for name into dir and returns its path.
// A hook that already carries a merged scan block has the block updated in
// place; with opts.Merge an unmanaged sh-compatible hook gets the block
// inserted after its shebang line.
func InstallHook(dir, name string, opts InstallHookOptions) (string, error) {
	flags, err := scanFlags(opts.LogLevel, opts.Verify, opts.Exclude, opts.VerifyHost)
	if err != nil {
		return "", err
	}
	script, err := hookScriptWithFlags(name, flags)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("failed to create hooks directory %q: %w", dir, err)
	}

	path := filepath.Join(dir, name)
	state, err := hookStateAt(path)
	if err != nil {
		return "", err
	}
	switch state {
	case HookStateMerged:
		return path, updateMergedHook(dir, name, path, flags)
	case HookStateUnmanaged:
		switch {
		case opts.Merge:
			return path, mergeIntoHook(dir, name, path, flags)
		case opts.Backup:
			if err := os.Rename(path, path+hookBackupSuffix); err != nil {
				return "", fmt.Errorf("failed to back up existing hook %q: %w", path, err)
			}
		case !opts.Force:
			return "", fmt.Errorf("hook %q already exists and is not managed by gh-secure-kit, use --merge to add the scan to it, --force to overwrite it or --backup to move it aside", path)
		}
	}

	if err := writeHookFile(dir, name, path, script, 0o755); err != nil {
		return "", err
	}
	return path, nil
}

// mergeIntoHook inserts the scan block right after the shebang line of the
// unmanaged hook at path.
func mergeIntoHook(dir, name, path string, flags string) error {
	// Never follow a symlink: the merged content would land outside dir.
	if info, err := os.Lstat(path); err == nil && info.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("hook %q is a symbolic link and cannot be merged, use --force to overwrite it or --backup to move it aside", path)
	}
	content, mode, err := readHookFile(path)
	if err != nil {
		return err
	}
	if _, _, found, err := findMergeBlock(content); err != nil {
		return fmt.Errorf("hook %q: %w", path, err)
	} else if found {
		return fmt.Errorf("hook %q already contains a gh-secure-kit block", path)
	}
	newline := strings.IndexByte(content, '\n')
	if newline < 0 {
		return fmt.Errorf("hook %q has no line after its shebang and cannot be merged, use --force to overwrite it or --backup to move it aside", path)
	}
	if !isMergeableShebang(content[:newline]) {
		return fmt.Errorf("hook %q is not a POSIX shell script and cannot be merged, use --force to overwrite it or --backup to move it aside", path)
	}
	block, err := mergeBlock(name, flags)
	if err != nil {
		return err
	}
	merged := content[:newline+1] + block + content[newline+1:]
	// Keep the original permissions but make sure the owner (git) can execute the hook.
	return writeHookFile(dir, name, path, merged, mode|0o100)
}

// updateMergedHook replaces the scan block already merged into the hook at
// path, leaving the rest of the script untouched.
func updateMergedHook(dir, name, path string, flags string) error {
	content, mode, err := readHookFile(path)
	if err != nil {
		return err
	}
	start, end, _, err := findMergeBlock(content)
	if err != nil {
		return fmt.Errorf("hook %q: %w", path, err)
	}
	block, err := mergeBlock(name, flags)
	if err != nil {
		return err
	}
	return writeHookFile(dir, name, path, content[:start]+block+content[end:], mode|0o100)
}

// readHookFile returns the content and permission bits of the hook at path.
func readHookFile(path string) (string, os.FileMode, error) {
	info, err := os.Stat(path)
	if err != nil {
		return "", 0, fmt.Errorf("failed to inspect hook %q: %w", path, err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return "", 0, fmt.Errorf("failed to read hook %q: %w", path, err)
	}
	return string(data), info.Mode().Perm(), nil
}

// writeHookFile atomically replaces the hook at path with content.
func writeHookFile(dir, name, path, content string, mode os.FileMode) error {
	// Write to a temporary file and rename it over the destination so we never
	// follow an existing symlink (which could place hook content outside dir)
	// and never leave a partially written hook behind.
	tmp, err := os.CreateTemp(dir, name+".tmp-*")
	if err != nil {
		return fmt.Errorf("failed to create temporary hook file in %q: %w", dir, err)
	}
	tmpPath := tmp.Name()
	defer func() { _ = os.Remove(tmpPath) }()
	if _, err := tmp.WriteString(content); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("failed to write hook %q: %w", path, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("failed to write hook %q: %w", path, err)
	}
	if err := os.Chmod(tmpPath, mode); err != nil {
		return fmt.Errorf("failed to set permissions of hook %q: %w", path, err)
	}
	if err := os.Rename(tmpPath, path); err != nil {
		return fmt.Errorf("failed to install hook %q: %w", path, err)
	}
	return nil
}

// UninstallHook removes the hook script for name from dir and reports whether
// a hook was removed. A merged scan block is removed from the hook, restoring
// the original script. A hook not generated by this tool is only removed when
// force is true.
func UninstallHook(dir, name string, force bool) (bool, error) {
	if !slices.Contains(HookNames, name) {
		return false, fmt.Errorf("unsupported hook %q, expected one of %s", name, strings.Join(HookNames, ", "))
	}
	path := filepath.Join(dir, name)
	state, err := hookStateAt(path)
	if err != nil {
		return false, err
	}
	switch state {
	case HookStateNotInstalled:
		return false, nil
	case HookStateMerged:
		content, mode, err := readHookFile(path)
		if err != nil {
			return false, err
		}
		start, end, _, err := findMergeBlock(content)
		if err != nil {
			return false, fmt.Errorf("hook %q: %w", path, err)
		}
		if err := writeHookFile(dir, name, path, content[:start]+content[end:], mode); err != nil {
			return false, err
		}
		return true, nil
	case HookStateUnmanaged:
		if !force {
			return false, fmt.Errorf("hook %q is not managed by gh-secure-kit, use --force to remove it", path)
		}
	}
	if err := os.Remove(path); err != nil {
		return false, fmt.Errorf("failed to remove hook %q: %w", path, err)
	}
	return true, nil
}

// HookStatuses reports the state of each of the given hooks in dir.
func HookStatuses(dir string, names []string) ([]HookStatus, error) {
	statuses := make([]HookStatus, 0, len(names))
	for _, name := range names {
		path := filepath.Join(dir, name)
		state, err := hookStateAt(path)
		if err != nil {
			return nil, err
		}
		statuses = append(statuses, HookStatus{Name: name, Path: path, State: state})
	}
	return statuses, nil
}

// hookHeader is the comment block that identifies a generated hook script.
func hookHeader(name string) string {
	return fmt.Sprintf(`#!/bin/sh
# %s
# Managed by: gh secure-kit secret-scanning local hook install
# Remove with: gh secure-kit secret-scanning local hook uninstall %s`, hookMarker, name)
}

// hookScript renders the shell script installed for the given hook. logLevel,
// when not empty, is passed as --log-level to the check command.
func hookScript(name, logLevel string, verify bool, excludedStatuses []string, githubHosts ...string) (string, error) {
	flags, err := scanFlags(logLevel, verify, excludedStatuses, githubHosts...)
	if err != nil {
		return "", err
	}
	return hookScriptWithFlags(name, flags)
}

// scanFlags renders the flags appended to the check command run by a hook.
func scanFlags(logLevel string, verify bool, excludedStatuses []string, githubHosts ...string) (string, error) {
	if err := ValidateVerificationOptions(verify, excludedStatuses, githubHosts...); err != nil {
		return "", err
	}
	logFlag, err := hookLogLevelFlag(logLevel)
	if err != nil {
		return "", err
	}
	if verify {
		logFlag += " --verify"
	}
	if len(githubHosts) == 1 && githubHosts[0] != "" {
		logFlag += " --verify-host " + shellquote.Join(githubHosts[0])
	}
	if len(excludedStatuses) > 0 {
		logFlag += " --exclude " + shellquote.Join(strings.Join(excludedStatuses, ","))
	}
	return logFlag, nil
}

// hookScriptWithFlags renders the standalone hook script for name, running
// the check command with the pre-rendered flags.
func hookScriptWithFlags(name, logFlag string) (string, error) {
	switch name {
	case "pre-commit":
		return hookHeader(name) + `
exec gh secure-kit secret-scanning local check` + logFlag + ` --staged
`, nil
	case "pre-push":
		// Git passes the pushed refs on stdin as
		// "<local ref> <local sha> <remote ref> <remote sha>" lines, and the
		// destination remote name as $1. Scan the exact commits being pushed so
		// a secret on any pushed branch (not just the checked-out HEAD) is
		// caught. A zero remote sha means a new ref, a zero local sha means a
		// deletion. For a new ref, exclude only the destination remote so a
		// commit that lives only on a different remote is still scanned.
		return hookHeader(name) + `
zero=0000000000000000000000000000000000000000
remote_name="$1"
while read -r local_ref local_sha remote_ref remote_sha; do
	[ "$local_sha" = "$zero" ] && continue
	if [ "$remote_sha" = "$zero" ]; then
		gh secure-kit secret-scanning local check` + logFlag + ` --unpushed --rev "$local_sha" --remote "$remote_name" || exit 1
	else
		gh secure-kit secret-scanning local check` + logFlag + ` --rev-range "$remote_sha..$local_sha" || exit 1
	fi
done
exit 0
`, nil
	default:
		return "", fmt.Errorf("unsupported hook %q, expected one of %s", name, strings.Join(HookNames, ", "))
	}
}

// mergeBlock renders the delimited scan block merged into an existing hook
// script. The block never ends the script on success, so the rest of the
// original hook keeps running; all its variables are prefixed with __ghsk_
// and unset afterwards, and the positional parameters are left untouched.
func mergeBlock(name, logFlag string) (string, error) {
	header := mergeBeginMarker + `
# Managed by: gh secure-kit secret-scanning local hook install --merge
# Remove with: gh secure-kit secret-scanning local hook uninstall ` + name + "\n"
	footer := mergeEndMarker + "\n"
	switch name {
	case "pre-commit":
		return header + `gh secure-kit secret-scanning local check` + logFlag + ` --staged || exit 1
` + footer, nil
	case "pre-push":
		// The pushed refs on stdin are needed both by the scan and by the rest
		// of the hook (e.g. "git lfs pre-push"), so buffer them, scan from a
		// here-document, and then replay them as the shell's stdin with exec.
		// Command substitution strips trailing newlines and the here-document
		// adds one back, which reproduces git's newline-terminated ref lines.
		// Empty input skips the scan entirely: replaying it would yield a
		// single blank line.
		return header + `__ghsk_zero=0000000000000000000000000000000000000000
__ghsk_remote_name="$1"
__ghsk_stdin=$(cat) || exit 1
if [ -n "$__ghsk_stdin" ]; then
	while read -r __ghsk_local_ref __ghsk_local_sha __ghsk_remote_ref __ghsk_remote_sha; do
		[ "$__ghsk_local_sha" = "$__ghsk_zero" ] && continue
		if [ "$__ghsk_remote_sha" = "$__ghsk_zero" ]; then
			gh secure-kit secret-scanning local check` + logFlag + ` --unpushed --rev "$__ghsk_local_sha" --remote "$__ghsk_remote_name" || exit 1
		else
			gh secure-kit secret-scanning local check` + logFlag + ` --rev-range "$__ghsk_remote_sha..$__ghsk_local_sha" || exit 1
		fi
	done <<__GHSK_EOF__
$__ghsk_stdin
__GHSK_EOF__
	exec <<__GHSK_EOF__
$__ghsk_stdin
__GHSK_EOF__
else
	exec </dev/null
fi
unset __ghsk_zero __ghsk_remote_name __ghsk_stdin __ghsk_local_ref __ghsk_local_sha __ghsk_remote_ref __ghsk_remote_sha
` + footer, nil
	default:
		return "", fmt.Errorf("unsupported hook %q, expected one of %s", name, strings.Join(HookNames, ", "))
	}
}

// isMergeableShebang reports whether line is a shebang that runs a POSIX
// compatible shell, either directly or through env.
func isMergeableShebang(line string) bool {
	rest, ok := strings.CutPrefix(strings.TrimRight(line, "\r"), "#!")
	if !ok {
		return false
	}
	fields := strings.Fields(rest)
	if len(fields) == 0 {
		return false
	}
	interpreter := filepath.Base(fields[0])
	args := fields[1:]
	if interpreter == "env" {
		interpreter = ""
		// Only -S (split string) and "--" are accepted: other env options
		// such as -u or -C take an operand that would otherwise be mistaken
		// for the interpreter.
		for i, f := range args {
			if f == "-S" || f == "--" {
				continue
			}
			if !strings.HasPrefix(f, "-") {
				interpreter = filepath.Base(f)
				args = args[i+1:]
			}
			break
		}
	}
	if !slices.Contains(mergeableShells, interpreter) {
		return false
	}
	// Reject shell options that make the shell run something other than the
	// hook file: -c executes a command string and -s reads commands from
	// stdin, in either case skipping the merged scan block.
	for _, a := range args {
		if a == "--" || !strings.HasPrefix(a, "-") || strings.HasPrefix(a, "--") {
			continue
		}
		if strings.ContainsAny(a[1:], "cs") {
			return false
		}
	}
	return true
}

// findMergeBlock locates the merged scan block in content and returns the
// byte range [start, end) covering its lines, including the trailing newline
// of the end marker. It returns an error unless the markers form exactly one
// begin line followed by one end line.
func findMergeBlock(content string) (start, end int, found bool, err error) {
	begins, ends := 0, 0
	offset := 0
	for offset < len(content) {
		next := strings.IndexByte(content[offset:], '\n')
		lineEnd := len(content)
		if next >= 0 {
			lineEnd = offset + next + 1
		}
		line := strings.TrimRight(content[offset:lineEnd], "\r\n")
		switch line {
		case mergeBeginMarker:
			begins++
			start = offset
		case mergeEndMarker:
			if begins == 0 {
				return 0, 0, false, errors.New("the gh-secure-kit block end marker appears before its begin marker")
			}
			ends++
			end = lineEnd
		}
		offset = lineEnd
	}
	switch {
	case begins == 0 && ends == 0:
		return 0, 0, false, nil
	case begins != 1 || ends != 1:
		return 0, 0, false, fmt.Errorf("the gh-secure-kit block markers are malformed (found %d begin and %d end markers)", begins, ends)
	}
	return start, end, true, nil
}

// hookLogLevelFlag renders the --log-level flag embedded in a generated hook,
// rejecting any value that is not a known log level so nothing arbitrary is
// written into the script.
func hookLogLevelFlag(logLevel string) (string, error) {
	if logLevel == "" {
		return "", nil
	}
	if _, err := logger.GetLogLevel(logLevel); err != nil {
		return "", fmt.Errorf("unsupported log level %q, expected one of %s", logLevel, strings.Join(logger.LogLevel, ", "))
	}
	return " --log-level " + strings.ToLower(logLevel), nil
}

// hookStateAt classifies the hook file at path.
func hookStateAt(path string) (HookState, error) {
	// A symlink is never a hook this tool generated; treat it as unmanaged so
	// it is not silently overwritten (and is never followed on write).
	if info, err := os.Lstat(path); err == nil && info.Mode()&os.ModeSymlink != 0 {
		return HookStateUnmanaged, nil
	}
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return HookStateNotInstalled, nil
	}
	if err != nil {
		return "", fmt.Errorf("failed to read hook %q: %w", path, err)
	}
	// Match the marker only as its own comment line so an unrelated hook that
	// merely mentions the marker text is not mistaken for a generated hook.
	if hasMarkerLine(string(data)) {
		return HookStateInstalled, nil
	}
	if _, _, found, err := findMergeBlock(string(data)); found && err == nil {
		return HookStateMerged, nil
	}
	return HookStateUnmanaged, nil
}

// hasMarkerLine reports whether content contains the generated marker on its
// own comment line.
func hasMarkerLine(content string) bool {
	markerLine := "# " + hookMarker
	for _, line := range strings.Split(content, "\n") {
		if strings.TrimRight(line, "\r") == markerLine {
			return true
		}
	}
	return false
}

// resolveGitDir returns the git directory for a worktree root, following the
// gitdir pointer used by linked worktrees and submodules.
func resolveGitDir(root string) (string, error) {
	dotGit := filepath.Join(root, ".git")
	info, err := os.Stat(dotGit)
	if err != nil {
		return "", fmt.Errorf("failed to locate git directory at %q: %w", dotGit, err)
	}
	if info.IsDir() {
		return dotGit, nil
	}
	data, err := os.ReadFile(dotGit)
	if err != nil {
		return "", fmt.Errorf("failed to read git directory pointer %q: %w", dotGit, err)
	}
	pointer, ok := strings.CutPrefix(strings.TrimSpace(string(data)), "gitdir:")
	if !ok {
		return "", fmt.Errorf("unexpected git directory pointer format in %q", dotGit)
	}
	gitDir := strings.TrimSpace(pointer)
	if !filepath.IsAbs(gitDir) {
		gitDir = filepath.Join(root, gitDir)
	}
	// In a linked worktree the pointer targets a per-worktree admin directory
	// (.git/worktrees/<name>), but git runs hooks from the common git
	// directory. Resolve commondir so hooks are installed where git looks.
	commonData, err := os.ReadFile(filepath.Join(gitDir, "commondir"))
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return gitDir, nil
		}
		return "", fmt.Errorf("failed to read commondir pointer in %q: %w", gitDir, err)
	}
	commonDir := strings.TrimSpace(string(commonData))
	if !filepath.IsAbs(commonDir) {
		commonDir = filepath.Join(gitDir, commonDir)
	}
	return filepath.Clean(commonDir), nil
}
